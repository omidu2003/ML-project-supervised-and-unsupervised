import pickle
import face_recognition
import matplotlib.pyplot as plt
import matplotlib.image as mpimg

# Load the saved KMeans model
model_load_path = "/kaggle/working/next"
with open(model_load_path, "rb") as f:
    kmeans = pickle.load(f)

def get_face_encoding(image_path):
    # Load the image using face_recognition
    image = face_recognition.load_image_file(image_path)

    # Find the face locations and encodings in the image
    face_locations = face_recognition.face_locations(image)
    face_encodings = face_recognition.face_encodings(image, face_locations)

    if len(face_encodings) > 0:
        return face_encodings[0]  # Return the first face encoding
    else:
        print("No face found in the image.")
        return None

def predict_cluster(image_path, kmeans_model):
    # Get the encoding for the new image
    encoding = get_face_encoding(image_path)

    if encoding is not None:
        # Predict the cluster for the new encoding using the loaded KMeans model
        cluster_label = kmeans_model.predict([encoding])
        return cluster_label[0]
    else:
        return None

