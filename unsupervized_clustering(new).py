import os
import cv2
import pickle
import numpy as np
import matplotlib.pyplot as plt

from deepface import DeepFace
from imutils import paths, build_montages
from sklearn.cluster import KMeans, DBSCAN
import face_recognition

# Define dataset paths
dataset_path = "/kaggle/input/test-d"
encodings_path = "/content/emotion_encodings.pickle"

# Initialize dataset storage
data = []
imagePaths = list(paths.list_images(dataset_path))

for (i, imagePath) in enumerate(imagePaths):
    print(f"[INFO] Processing image {i + 1}/{len(imagePaths)}: {imagePath}")

    # Read the image
    image = cv2.imread(imagePath)
    rgb_image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

    # Detect faces
    boxes = face_recognition.face_locations(rgb_image, model='hog')

    # Compute facial encodings
    encodings = face_recognition.face_encodings(rgb_image, boxes)

    # Extract emotion using DeepFace
    try:
        emotion_result = DeepFace.analyze(imagePath, actions=['emotion'], enforce_detection=False)
        emotion = emotion_result[0]['dominant_emotion']
    except:
        emotion = "unknown"

    # Store encodings and emotions
    for (box, enc) in zip(boxes, encodings):
        data.append({"imagePath": imagePath, "loc": box, "encoding": enc, "emotion": emotion})

    # Draw face boxes
    for (top, right, bottom, left) in boxes:
        cv2.rectangle(rgb_image, (left, top), (right, bottom), (0, 255, 0), 3)

    # Display images with detected faces
    plt.figure(figsize=(6, 6))
    plt.imshow(rgb_image)
    plt.axis("off")
    plt.title(f"Emotion: {emotion}")
    plt.show()

# Save encodings
with open(encodings_path, "wb") as f:
    pickle.dump(data, f)

