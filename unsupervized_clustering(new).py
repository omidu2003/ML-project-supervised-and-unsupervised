"""# Clustering with kmeans"""

import os
import cv2
import pickle
import numpy as np
import matplotlib.pyplot as plt
from sklearn.cluster import KMeans
from imutils import build_montages

# Specify paths
ENCODINGS_PATH = "/content/encodings.pickle"
CLUSTERING_RESULT_PATH = "/kaggle/working/"

# Create Clustering Results directory if it doesn't exist
if not os.path.exists(CLUSTERING_RESULT_PATH):
    os.mkdir(CLUSTERING_RESULT_PATH)

# Load encodings
print("[INFO] Loading encodings...")
data = pickle.load(open(ENCODINGS_PATH, "rb"))

# Extract encodings from data
encodings = np.array([d["encoding"] for d in data])

# Perform KMeans clustering
print("[INFO] Clustering...")
kmeans = KMeans(n_clusters=5, random_state=42, n_init=10)  # Adjust clusters if needed
labels = kmeans.fit_predict(encodings)

# Determine unique label IDs
labelIDs = np.unique(labels)
numUniqueFaces = len(labelIDs)
print(f"[INFO] Unique faces detected: {numUniqueFaces}")

# Loop over unique label IDs
for labelID in labelIDs:
    print(f"[INFO] Faces for cluster: {labelID}")
    idxs = np.where(labels == labelID)[0]
    idxs = np.random.choice(idxs, size=min(25, len(idxs)), replace=False)

    # Initialize list of faces
    faces = []

    # Loop over sampled indexes
    for i in idxs:
        image = cv2.imread(data[i]["imagePath"])
        (top, right, bottom, left) = data[i]["loc"]
        face = image[top:bottom, left:right]

        # Resize face and add to faces list
        face = cv2.resize(face, (96, 96))
        faces.append(face)

    # Create montage
    montage = build_montages(faces, (96, 96), (5, 5))[0]

    # Save the output montage
    title = f"Cluster_{labelID}"
    output_path = os.path.join(CLUSTERING_RESULT_PATH, title + '.jpg')
    cv2.imwrite(output_path, montage)

    # Display the montage using matplotlib
    plt.figure(figsize=(6, 6))
    plt.imshow(cv2.cvtColor(montage, cv2.COLOR_BGR2RGB))
    plt.axis("off")
    plt.title(title)
    plt.show()

print(f"[INFO] Clustering results saved in {CLUSTERING_RESULT_PATH}")

